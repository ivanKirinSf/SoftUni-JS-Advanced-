function toggle(){

    let extraReff = document.getElementById("extra");

    let buttonReff = document.querySelector(".button");

    if(extraReff.display.style === "none"){

        extraReff.display.style = "block";
        buttonReff.display.style = "Less"

    }else{

        extraReff.display.style = "block";
        buttonReff.display.style = "Less";

    }
}
